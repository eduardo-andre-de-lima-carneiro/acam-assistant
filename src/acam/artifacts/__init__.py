"""Academic artifacts generated from the structured catalog (never hand-maintained)."""

from __future__ import annotations

import csv
import io
import json

from .. import __version__, models
from ..models import value_of
from ..storage import Project

GENERATED_NOTE = ("> Generated by ACAM Assistant {v} on {at} from the structured catalog. "
                  "Machine-extracted content requires researcher validation.")


def _header(title: str) -> list[str]:
    return [f"# {title}", "", GENERATED_NOTE.format(v=__version__, at=models.now_iso()), ""]


def _cell(text, limit: int = 160) -> str:
    if text in (None, "", [], "unknown"):
        return "—"
    if isinstance(text, list):
        text = "; ".join(str(t) for t in text)
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _first_author(meta: dict) -> str:
    authors = value_of(meta, "authors", [])
    if not authors:
        return "—"
    return authors[0] + (" et al." if len(authors) > 1 else "")


def _items(analysis: dict | None, key: str, n: int = 2) -> list[str]:
    if not analysis:
        return []
    return [i["text"] if isinstance(i, dict) else str(i) for i in (analysis.get(key) or [])[:n]]


def matrix_rows(project: Project, include_rejected: bool = False) -> list[dict]:
    rows = []
    for s in project.sources():
        if s["status"] == "rejected" and not include_rejected:
            continue
        a = project.read_analysis(s["id"])
        meta = s["metadata"]
        rows.append({
            "id": s["id"],
            "author": _first_author(meta),
            "year": value_of(meta, "publication_year", ""),
            "type": s["type"],
            "title": value_of(meta, "title", s["original_file"]["name"]),
            "objective": (a or {}).get("research_objective"),
            "methodology": ((a or {}).get("methodology") or {}).get("approach"),
            "findings": _items(a, "main_findings"),
            "gaps": _items(a, "research_gaps"),
            "status": s["status"],
        })
    return rows


def literature_matrix(project: Project, include_rejected: bool = False) -> str:
    rows = matrix_rows(project, include_rejected)
    lines = _header(f"Literature Matrix — {project.info()['title']}")
    lines += ["| ID | Author | Year | Type | Title | Objective | Methodology | Main Findings | Research Gaps | Status |",
              "| --- | --- | ---: | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append("| " + " | ".join([
            r["id"], _cell(r["author"]), _cell(r["year"]), r["type"], _cell(r["title"], 90),
            _cell(r["objective"]), _cell(r["methodology"]), _cell(r["findings"], 220),
            _cell(r["gaps"], 220), r["status"]]) + " |")
    if not rows:
        lines.append("| — | — | — | — | — | — | — | — | — | — |")
    return "\n".join(lines) + "\n"


def literature_matrix_csv(project: Project, include_rejected: bool = False) -> str:
    buf = io.StringIO()
    fields = ["id", "author", "year", "type", "title", "objective", "methodology", "findings",
              "gaps", "status"]
    writer = csv.DictWriter(buf, fieldnames=fields)
    writer.writeheader()
    for r in matrix_rows(project, include_rejected):
        writer.writerow({k: "; ".join(v) if isinstance(v, list) else v for k, v in r.items()})
    return buf.getvalue()


def reference_entries(project: Project, include_rejected: bool = False) -> list[tuple[dict, dict]]:
    """(source record, reference) pairs in ABNT alphabetical order."""
    entries = []
    for s in project.sources():
        if s["status"] == "rejected" and not include_rejected:
            continue
        ref = s.get("bibliographic_reference") or {}
        if ref.get("text"):
            entries.append((ref["text"].replace("*", "").upper(), s, ref))
    entries.sort(key=lambda e: e[0])
    return [(s, ref) for _, s, ref in entries]


def references_list(project: Project, include_rejected: bool = False) -> str:
    lines = _header(f"References — {project.info()['title']}")
    for s, ref in reference_entries(project, include_rejected):
        flags = []
        if ref.get("missing_fields"):
            flags.append("missing: " + ", ".join(ref["missing_fields"]))
        if ref.get("requires_validation"):
            flags.append("unvalidated")
        suffix = f" <!-- {s['id']}{': ' + '; '.join(flags) if flags else ''} -->"
        lines += [ref["text"] + suffix, ""]
    return "\n".join(lines)


def _prov(entry: dict) -> str:
    if entry.get("validated"):
        return "validated"
    conf = entry.get("confidence")
    return f"{entry.get('source', 'unknown')}" + (f", confidence {conf}" if conf is not None else "")


def _evidence_lines(items: list) -> list[str]:
    out = []
    for i in items or []:
        if isinstance(i, str):
            out.append(f"- {i}")
            continue
        loc = ", ".join(x for x in [i.get("section") and f"§ {i['section']}",
                                    i.get("page") and f"p. {i['page']}"] if x)
        out.append(f"- {i['text']}" + (f" _({loc})_" if loc else ""))
        if i.get("quote") and i["quote"] != i["text"]:
            out.append(f"  > {i['quote']}")
    return out or ["- unknown"]


def source_report(project: Project, source_id: str) -> str:
    s = project.get_source(source_id)
    a = project.read_analysis(source_id)
    meta = s["metadata"]
    lines = _header(value_of(meta, "title", s["original_file"]["name"]))
    lines += ["## Bibliographic reference", "",
              (s.get("bibliographic_reference") or {}).get("text", "—"), "",
              "## Metadata (source evidence)", "", "| Field | Value | Provenance |", "| --- | --- | --- |"]
    for name in models.METADATA_FIELDS:
        entry = meta.get(name) or {}
        if entry.get("value") not in (None, "", []):
            lines.append(f"| {name} | {_cell(entry['value'], 200)} | {_prov(entry)} |")
    lines += ["", f"- **Type:** {s['type']}  ", f"- **Status:** {s['status']}  ",
              f"- **Original file:** {s['original_file']['name']}  ",
              f"- **Markdown:** `{s.get('markdown_file')}`", ""]
    if s["abstract"].get("original_abstract"):
        lines += ["## Original abstract (author)", "", s["abstract"]["original_abstract"], ""]
    if not a:
        lines += ["_Not analyzed yet. Run `acam analyze`._", ""]
    else:
        m = a.get("methodology") or {}
        proc = a["processing"]
        lines += [
            "## Generated summary (machine-generated — requires validation)", "",
            a.get("summary") or "unknown", "",
            f"_Engine: {a['engine']}; model: {proc.get('analysis_model') or 'n/a'}; "
            f"prompt: {proc.get('prompt_version')}; at: {proc.get('processed_at')}_", "",
            "## Research design", "",
            f"- **Problem:** {a.get('research_problem', 'unknown')}",
            f"- **Objective:** {a.get('research_objective', 'unknown')}",
            f"- **Theoretical framework:** {a.get('theoretical_framework', 'unknown')}",
            f"- **Methodology:** {m.get('approach', 'unknown')} — {m.get('description', 'unknown')}",
            f"- **Population/sample:** {m.get('population_sample', 'unknown')}",
            f"- **Data collection:** {m.get('data_collection', 'unknown')}",
            f"- **Analysis method:** {m.get('analysis_method', 'unknown')}", "",
            "### Research questions", "", *_evidence_lines(a.get("research_questions")), "",
            "## Main findings", "", *_evidence_lines(a.get("main_findings")), "",
            "## Contributions", "", *_evidence_lines(a.get("contributions")), "",
            "## Limitations", "", *_evidence_lines(a.get("limitations")), "",
            "## Research gaps (hypotheses for validation)", "", *_evidence_lines(a.get("research_gaps")), "",
            "## Conclusions", "", a.get("conclusions") or "unknown", "",
            "## Future research", "", *_evidence_lines(a.get("future_research")), "",
            "## Concepts and theories", "",
            f"- **Concepts:** {_cell(a.get('relevant_concepts'), 500)}",
            f"- **Theories:** {_cell(a.get('theories'), 500)}",
            f"- **Frequently cited authors:** {_cell(a.get('frequently_cited_authors'), 500)}", "",
            "## Relevance to the project", "", a.get("relevance_to_project") or "unknown", "",
        ]
        if a.get("warnings"):
            lines += ["## Analysis warnings", "", *[f"- {w}" for w in a["warnings"]], ""]
    lines += ["## Researcher notes", "", s.get("researcher_notes") or "_none_", ""]
    return "\n".join(lines)


def export_catalog(project: Project) -> str:
    """Single JSON document in the shape of the specification's "Structured JSON Model"."""
    sources = []
    for s in project.sources():
        sources.append({**s, "analysis_result": project.read_analysis(s["id"])})
    return json.dumps({"project": project.info(), "sources": sources}, ensure_ascii=False, indent=2) + "\n"
